"""Actual local API + existing workspace: directory, lazy history and role UI."""
from datetime import datetime,timezone
from playwright.sync_api import sync_playwright,expect

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    for login in ['one','admin','boss']:
        page=browser.new_page(locale='ru-RU',viewport={'width':1366,'height':900})
        page.set_default_timeout(60000)
        page.set_default_navigation_timeout(120000)
        page.clock.set_fixed_time(datetime(2026,10,19,12,tzinfo=timezone.utc))
        page.route('https://cdn.jsdelivr.net/npm/chart.js',lambda r:r.fulfill(path='/workspace/.calltrack-tools/chart.umd.min.js',content_type='application/javascript'))
        requests=[];errors=[]
        page.on('request',lambda r:requests.append(r.url))
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto('http://127.0.0.1:8090/vr/calltrack/analizmop/')
        page.locator('#authLogin').fill(login+'@example.test');page.locator('#authPin').fill('12345678');page.locator('#authForm button').click()
        expect(page.locator('#appShell')).to_be_visible()
        page.locator('[data-tab=clients]').click()
        expect(page.locator('#clientsList .client-catalog-row')).to_have_count(50,timeout=60000)
        for endpoint in ['client_events.php','client_purchases.php','client_max_history.php']:
            assert not any(endpoint in url for url in requests),(endpoint,requests)
        assert len([url for url in requests if 'clients_list.php' in url])==1,requests
        if login=='one':expect(page.locator('#clientsManagerLabel')).to_be_hidden()
        else:
            expect(page.locator('#clientsManagerLabel')).to_be_visible()
            page.locator('#clientsManager').select_option('2')
            expect(page.locator('#clientsList')).to_contain_text('Бета Каталог')
            expect(page.locator('#clientsList')).not_to_contain_text('Альфа Каталог')
            page.locator('#clientsManager').select_option('')
        page.locator('#clientsNext').click()
        expect(page.locator('#clientsPage')).to_contain_text('Страница 2')
        page.locator('#clientsSearch').fill('Без звонков')
        expect(page.locator('#clientsList .client-catalog-row')).to_have_count(1)
        page.get_by_role('button',name='Без звонков',exact=False).click()
        expect(page.locator('#clientHistoryModal')).to_have_class('comment-modal open')
        expect(page.locator('#clientIdentityStatus')).to_have_text('')
        expect(page.locator('#clientUnknown')).to_be_hidden()
        expect(page.locator('#clientSummaryKpis')).to_contain_text('Количество продаж',timeout=60000)
        page.locator('#clientHistoryCloseBtn').click()
        page.locator('#clientsSearch').fill('9000000001')
        expect(page.locator('#clientsList .client-catalog-row')).to_have_count(1)
        expect(page.locator('[data-catalog-client="catalog-a"]')).to_be_visible()
        if login=='one':page.screenshot(path='/workspace/.calltrack-tools/clients-catalog.png',full_page=True)
        page.locator('[data-catalog-client="catalog-a"]').click()
        history=page.locator('#clientHistoryList')
        expect(history).to_contain_text('Catalog note')
        expect(history).to_contain_text('Catalog outgoing email')
        expect(history).to_contain_text('Переписка MAX',timeout=60000)
        expect(history).to_contain_text('Исходящие: 1')
        expect(history).to_contain_text('18.10.2026 · 20:30')
        if login=='one':page.screenshot(path='/workspace/.calltrack-tools/clients-catalog-history.png',full_page=True)
        page.locator('#clientPurchasesTab').click()
        expect(page.locator('#purchaseTree')).to_contain_text('2026',timeout=60000)
        page.locator('#clientHistoryCloseBtn').click()
        # The original entry point still uses the same modal/workspace and interaction APIs.
        page.locator('[data-tab=clientCalls]').click()
        if login!='one':
            page.locator('#clientManagerTags [data-manager="One"]').click()
        page.get_by_role('button',name='Покупатель',exact=True).click()
        expect(page.locator('#clientHistoryList')).to_contain_text('Test note')
        expect(page.locator('#clientSummaryKpis')).to_contain_text('Количество продаж',timeout=60000)
        page.locator('#clientHistoryCloseBtn').click()
        page.locator('[data-tab=clients]').click()
        if login=='one':
            page.set_viewport_size({'width':390,'height':844})
            page.locator('#clientsSearch').fill('несуществующий клиент')
            expect(page.locator('#clientsStatus')).to_have_text('Клиенты не найдены')
            page.route('**/api/clients_list.php*',lambda r:r.abort())
            page.locator('#clientsSort').select_option('name_asc')
            expect(page.locator('#clientsRetry')).to_be_visible()
            page.unroute('**/api/clients_list.php*')
            page.locator('#clientsSearch').fill('9000000001')
            expect(page.locator('[data-catalog-client="catalog-a"]')).to_be_visible()
            assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'), page.evaluate('[...document.querySelectorAll("body *")].filter(e=>e.getBoundingClientRect().right>innerWidth).slice(0,8).map(e=>[e.id,e.className,e.getBoundingClientRect().width])')
        assert not errors,errors
        page.close()
    browser.close()
print('client_catalog_browser: three roles, one list request/no eager history, pagination/search/filter, no-call client, shared modal, calls/email/sales/MAX, old entry, mobile/errors OK')
